import "@testing-library/jest-dom/vitest";

// matchMedia is not available in jsdom; provide a default mobile (matches=false) stub
Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
});
